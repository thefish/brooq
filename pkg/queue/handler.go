package queue

import "context"

// Handler — обработчик темы: исполняет одну попытку взятого задания.
//
// Движок передаёт обработчику Claim, а не Job: номер попытки и колбэк
// OnSucceeded известны только после взятия (D9). Обработчик сообщает
// исход через возвращённую ошибку:
//
//   - nil — успех: задание становится done безусловно;
//   - обычная ошибка — сбой попытки: failed с отсрочкой или dead, если
//     попытки исчерпаны;
//   - MustDelay(d) — failed с назначенной отсрочкой (не длиннее
//     BackoffMax); на последней попытке — dead;
//   - ErrMustPreserveAttempt — failed без расхода попытки;
//   - ErrMustCancelTask — canceled независимо от остатка попыток.
//
// Причину прерывания контекста обработчику разбирать не нужно: он
// возвращает ctx.Err(), а исход по context.Cause определяет движок (D15).
type Handler interface {
	// Handle исполняет попытку задания. Возвращённая ошибка задаёт
	// исход попытки; паника перехватывается движком и считается сбоем
	// попытки, воркер при этом остаётся работоспособным.
	Handle(ctx context.Context, job Claim) error
}
